# @title 6. JAX Energy Functionals (KS-DFT Components)

def compute_whitening(S: np.ndarray):
    evals, evecs = np.linalg.eigh(S)
    evals = np.clip(evals, 1e-12, None)
    D = evecs @ np.diag(evals ** -0.5)
    return jnp.array(D, dtype=jnp.float32)

@jit
def W_to_C(W: jnp.ndarray, D: jnp.ndarray) -> jnp.ndarray:
    N = W.shape[0]
    Q, _ = jnp.linalg.qr(W.T)
    Q_N  = Q[:, :N].T
    return Q_N @ D.T

@jit
def eval_psi(C: jnp.ndarray, phi: jnp.ndarray) -> jnp.ndarray:
    return phi @ C.T

@jit
def eval_rho(psi: jnp.ndarray, occ: float = 2.0) -> jnp.ndarray:
    """Calculates density using the orbital occupation number."""
    return occ * jnp.sum(psi ** 2, axis=-1)

@jit
def kinetic_energy(C: jnp.ndarray, phi: jnp.ndarray, phi_grad: jnp.ndarray, weights: jnp.ndarray, occ: float = 2.0) -> jnp.ndarray:
    psi_grad = jnp.einsum("ij,njk->nik", C, phi_grad)
    grad_sq = jnp.sum(psi_grad ** 2, axis=-1)
    integrand = occ * jnp.sum(grad_sq, axis=-1)
    return 0.5 * jnp.dot(weights, integrand)

@jit
def external_energy(rho: jnp.ndarray, coords: jnp.ndarray, weights: jnp.ndarray, atom_coords: jnp.ndarray, atom_charges: jnp.ndarray) -> jnp.ndarray:
    diff = coords[:, None, :] - atom_coords[None, :, :]
    dist = jnp.sqrt(jnp.sum(diff ** 2, axis=-1) + 1e-18)
    v_ext = -jnp.sum(atom_charges[None, :] / dist, axis=-1)
    return jnp.dot(weights, rho * v_ext)

@partial(jit, static_argnums=(4, 5))
def hartree_energy_batch_coords(rho_batch: jnp.ndarray, weights_batch: jnp.ndarray, coords_batch: jnp.ndarray, coords_batch2: jnp.ndarray, n_total: int, m_batch: int) -> jnp.ndarray:
    diff = coords_batch[:, None, :] - coords_batch2[None, :, :]
    # SOFT-CORE FIX: + 1e-4 prevents 1/r singularity
    dist = jnp.sqrt(jnp.sum(diff ** 2, axis=-1) + 1e-4)
    scale = (n_total ** 2) / (m_batch ** 2)
    rho_w1 = rho_batch  * weights_batch
    rho_w2 = rho_batch  * weights_batch
    mask = 1.0 - jnp.eye(m_batch)
    return 0.5 * scale * jnp.sum(mask * rho_w1[:, None] * rho_w2[None, :] / dist)

@jit
def hartree_energy_full(rho: jnp.ndarray, weights: jnp.ndarray, coords: jnp.ndarray) -> jnp.ndarray:
    diff = coords[:, None, :] - coords[None, :, :]
    # SOFT-CORE FIX: + 1e-4
    dist = jnp.sqrt(jnp.sum(diff ** 2, axis=-1) + 1e-4)
    mask = 1.0 - jnp.eye(coords.shape[0])
    rho_w = rho * weights
    return 0.5 * jnp.sum(mask * rho_w[:, None] * rho_w[None, :] / dist)

@jit
def analytical_hartree_energy(C: jnp.ndarray, eri: jnp.ndarray, occ: float = 2.0) -> jnp.ndarray:
    """Exact Hartree energy using analytical ERIs."""
    P = occ * (C.T @ C)  # Density matrix
    return 0.5 * jnp.einsum('ij,kl,ijkl->', P, P, eri)

@jit
def analytical_hartree_energy_spin(C_a: jnp.ndarray, C_b: jnp.ndarray, eri: jnp.ndarray) -> jnp.ndarray:
    """Exact Spin-polarized Hartree energy."""
    P = 1.0 * (C_a.T @ C_a) + 1.0 * (C_b.T @ C_b)
    return 0.5 * jnp.einsum('ij,kl,ijkl->', P, P, eri)

@jit
def lda_exc_energy(rho: jnp.ndarray, weights: jnp.ndarray) -> jnp.ndarray:
    rho_safe = jnp.clip(rho, 1e-18, None)
    Cx = -0.7385587663820224
    eps_x = Cx * rho_safe ** (1.0/3.0)
    rs = (3.0 / (4.0 * jnp.pi * rho_safe)) ** (1.0/3.0)

    A, x0, b, c = 0.0310907, -0.10498, 3.72744, 12.9352

    # FIX: Split onto separate lines so 'x' exists before 'X' is calculated
    X0 = x0**2 + b*x0 + c
    x = jnp.sqrt(rs)
    X = x**2 + b*x + c

    eps_c = A * (jnp.log(x**2 / X) + 2*b/jnp.sqrt(4*c - b**2) * jnp.arctan(jnp.sqrt(4*c - b**2)/(2*x+b)) - (b*x0/X0) * (jnp.log((x-x0)**2/X) + 2*(2*x0+b)/jnp.sqrt(4*c - b**2) * jnp.arctan(jnp.sqrt(4*c - b**2)/(2*x+b))))
    return jnp.dot(weights, rho * (eps_x + eps_c))

@jit
def lsda_exc_energy(rho_a: jnp.ndarray, rho_b: jnp.ndarray, weights: jnp.ndarray) -> jnp.ndarray:
    rho = rho_a + rho_b
    Cx = -0.7385587663820224
    rho_a_s, rho_b_s = jnp.clip(rho_a, 1e-18, None), jnp.clip(rho_b, 1e-18, None)
    eps_x = 0.5 * (Cx * (2*rho_a_s)**(1/3) + Cx * (2*rho_b_s)**(1/3))

    rho_safe = jnp.clip(rho, 1e-18, None)
    rs = (3.0 / (4.0 * jnp.pi * rho_safe)) ** (1.0/3.0)

    A, x0, b, c = 0.0310907, -0.10498, 3.72744, 12.9352

    # FIX: Split onto separate lines
    X0 = x0**2 + b*x0 + c
    x = jnp.sqrt(rs)
    X = x**2 + b*x + c

    eps_c = A * (jnp.log(x**2 / X) + 2*b/jnp.sqrt(4*c - b**2) * jnp.arctan(jnp.sqrt(4*c - b**2)/(2*x+b)) - (b*x0/X0) * (jnp.log((x-x0)**2/X) + 2*(2*x0+b)/jnp.sqrt(4*c - b**2) * jnp.arctan(jnp.sqrt(4*c - b**2)/(2*x+b))))
    return jnp.dot(weights, rho * (eps_x + eps_c))

# @title 7. Neural Network Modules (Neural Basis + Neural Exc)
# ─────────────────────────────────────────────────────────────
# Method 1 uses:
#   NeuralBasisScaler  — local scaling transformation  f_θ(r) = λ_θ(r) r
#   NeuralXC           — neural exchange-correlation functional
# ─────────────────────────────────────────────────────────────

class NeuralBasisScaler(nn.Module):
    """
    Implements the Neural Local Scaling Transformation (Section 4 of D4FT paper).

    Given a 3D coordinate r, computes:
        λ_θ(r) = α × sigmoid( g_θ(r) )     where  g_θ : R³ → R
        f_θ(r) = λ_θ(r) × r

    The transformed basis function becomes:
        φ̃_i(r) = |det J_{f_θ}(r)|^{1/2} × φ_i(f_θ(r))

    The Jacobian determinant factor ensures the overlap matrix S stays
    UNCHANGED w.r.t. θ, so the whitening matrix D doesn't need recomputation.
    """
    hidden_dim: int = NBASIS_HIDDEN
    depth: int      = NBASIS_DEPTH
    alpha: float    = ALPHA_SCALE

    @nn.compact
    def __call__(self, r: jnp.ndarray) -> jnp.ndarray:
        """
        Args:
            r: (..., 3) grid coordinates
        Returns:
            r_transformed: (..., 3) scaled coordinates  f_θ(r)
        """
        x = r
        for _ in range(self.depth - 1):
            x = nn.Dense(self.hidden_dim)(x)
            x = nn.tanh(x)
        g = nn.Dense(1)(x)[..., 0]          # scalar output g_θ(r)
        lam = self.alpha * nn.sigmoid(g)    # λ_θ(r)  — positive scalar
        return lam[..., None] * r           # f_θ(r)  — scaled coords

    def transform_phi(self, r: jnp.ndarray,
                      phi_fn,
                      params) -> jnp.ndarray:
        """
        Apply the neural scaling and compute the Jacobian determinant factor.
        Returns scaled basis values: φ̃(r) = |det J|^{1/2} φ(f_θ(r))

        phi_fn(r_transformed) should return (n, B) basis values.
        """
        # Jacobian of f_θ(r) w.r.t. r  — shape (n, 3, 3)
        def single_jac(ri):
            return jax.jacobian(lambda r_: self.apply(params, r_))(ri)

        jac = vmap(single_jac)(r)          # (n, 3, 3)
        det = jnp.abs(jnp.linalg.det(jac))  # (n,)

        r_scaled   = self.apply(params, r)  # (n, 3)
        phi_scaled = phi_fn(r_scaled)       # (n, B)  (caller provides phi_fn)

        return (det ** 0.5)[:, None] * phi_scaled   # (n, B)


class NeuralXC(nn.Module):
    """
    Neural exchange-correlation functional.
    Architecture: MLP with residual connections.
    """
    hidden_dim: int = NXC_HIDDEN
    depth: int      = NXC_DEPTH

    @nn.compact
    def __call__(self, rho: jnp.ndarray) -> jnp.ndarray:
        rho_safe = jnp.clip(rho, 1e-12, None)

        feat = jnp.stack([
            rho_safe,
            rho_safe ** (1.0/3.0),
            jnp.log(1.0 + rho_safe),
        ], axis=-1)

        x = feat
        for _ in range(self.depth - 1):
            x = nn.Dense(self.hidden_dim)(x)
            x = nn.silu(x)

        # CRITICAL FIX: Initialize the final layer to exactly ZERO.
        # This ensures the network starts as a perfect replica of standard LDA,
        # preventing the inner physics loop from exploding on the first step.
        eps_xc = nn.Dense(
            1,
            kernel_init=jax.nn.initializers.zeros,
            bias_init=jax.nn.initializers.zeros
        )(x)[..., 0]

        # Residual: baseline LDA
        Cx = -0.7385587663820224
        lda_x = Cx * rho_safe ** (1.0/3.0)

        return eps_xc + lda_x

def neural_xc_energy(neural_xc_model: NeuralXC,
                     nxc_params: dict,
                     rho: jnp.ndarray,
                     weights: jnp.ndarray) -> jnp.ndarray:
    """E_xc = ∫ ρ(r) ε_xc(ρ(r)) dr  using neural ε_xc."""
    eps_xc = neural_xc_model.apply(nxc_params, rho)   # (n,)
    return jnp.dot(weights, rho * eps_xc)


