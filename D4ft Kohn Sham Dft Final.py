import itertools, math

def _icosahedron_vertices():
    phi = (1 + math.sqrt(5)) / 2
    verts = []
    for s1, s2 in itertools.product([1, -1], [1, -1]):
        verts.append([0,  s1,  s2 * phi])
        verts.append([s1 * phi, 0, s2])
        verts.append([s1,  s2 * phi, 0])
    return np.array(verts, dtype=float)

def fullerene_coords(tag: str) -> str:
    """
    Generate approximate Fullerene Cn coordinates by distributing n
    carbons on a sphere of appropriate radius.  Uses a Fibonacci lattice
    for a uniform distribution — good enough for a timing benchmark.
    """
    n = int(tag[1:])
    r = 3.5 * (n / 60) ** (1/3)   # empirical radius scaling (Å)
    golden = (1 + math.sqrt(5)) / 2
    coords = []
    for i in range(n):
        theta = math.acos(1 - 2 * (i + 0.5) / n)
        phi   = 2 * math.pi * i / golden
        x = r * math.sin(theta) * math.cos(phi)
        y = r * math.sin(theta) * math.sin(phi)
        z = r * math.cos(theta)
        coords.append(f"C  {x:.6f}  {y:.6f}  {z:.6f}")
    return "\n".join(coords)

