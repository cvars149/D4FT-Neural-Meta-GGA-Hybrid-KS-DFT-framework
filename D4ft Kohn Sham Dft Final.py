# @title 8. Total KS Energy Functions (Methods 1, 2)

def make_total_energy_fn(phi_np, phi_grad_np, coords_np, weights_np, atom_coords_np, atom_charges_np, D_jnp, E_nuc, eri_np, use_neural_xc=False, neural_xc_model=None, batch_size=None):
    phi, phi_grad = jnp.array(phi_np, dtype=jnp.float32), jnp.array(phi_grad_np, dtype=jnp.float32)
    coords, weights = jnp.array(coords_np, dtype=jnp.float32), jnp.array(weights_np, dtype=jnp.float32)
    a_coords, a_charges = jnp.array(atom_coords_np, dtype=jnp.float32), jnp.array(atom_charges_np, dtype=jnp.float32)
    eri = jnp.array(eri_np, dtype=jnp.float32)
    n_total = len(weights_np)

    def total_energy(W: jnp.ndarray, extra_params=None, key: jnp.ndarray = None) -> jnp.ndarray:
        C = W_to_C(W, D_jnp)
        psi = eval_psi(C, phi)
        rho = eval_rho(psi, occ=2.0)

        E_kin = kinetic_energy(C, phi, phi_grad, weights, occ=2.0)
        E_ext = external_energy(rho, coords, weights, a_coords, a_charges)

        if batch_size is not None and key is not None:
            # Scalable grid approach for massive Exp 3 molecules
            m = batch_size
            idx = jax.random.choice(key, n_total, shape=(m,), replace=False)
            E_H = hartree_energy_batch_coords(rho[idx], weights[idx], coords[idx], coords[idx], n_total, m)
        else:
            # Exact analytical approach for Exp 1 & 2
            E_H = analytical_hartree_energy(C, eri, occ=2.0)

        if use_neural_xc and extra_params is not None:
            E_xc = neural_xc_energy(neural_xc_model, extra_params, rho, weights)
        else:
            E_xc = lda_exc_energy(rho, weights)

        return E_kin + E_ext + E_H + E_xc + E_nuc
    return total_energy

def make_total_energy_fn_spin(phi_a_np, phi_grad_a_np, phi_b_np, phi_grad_b_np, coords_np, weights_np, atom_coords_np, atom_charges_np, D_a, D_b, E_nuc, eri_np, batch_size=None):
    phi_a, phi_ga = jnp.array(phi_a_np, dtype=jnp.float32), jnp.array(phi_grad_a_np, dtype=jnp.float32)
    phi_b, phi_gb = jnp.array(phi_b_np, dtype=jnp.float32), jnp.array(phi_grad_b_np, dtype=jnp.float32)
    coords, weights = jnp.array(coords_np, dtype=jnp.float32), jnp.array(weights_np, dtype=jnp.float32)
    a_coords, a_chgs = jnp.array(atom_coords_np, dtype=jnp.float32), jnp.array(atom_charges_np, dtype=jnp.float32)
    eri = jnp.array(eri_np, dtype=jnp.float32)

    def total_energy_spin(W_a: jnp.ndarray, W_b: jnp.ndarray, key=None) -> jnp.ndarray:
        C_a, C_b = W_to_C(W_a, D_a), W_to_C(W_b, D_b)
        psi_a, psi_b = eval_psi(C_a, phi_a), eval_psi(C_b, phi_b)

        rho_a = eval_rho(psi_a, occ=1.0)
        rho_b = eval_rho(psi_b, occ=1.0)
        rho = rho_a + rho_b

        E_kin = (kinetic_energy(C_a, phi_a, phi_ga, weights, occ=1.0) + kinetic_energy(C_b, phi_b, phi_gb, weights, occ=1.0))
        E_ext = external_energy(rho, coords, weights, a_coords, a_chgs)
        E_H = analytical_hartree_energy_spin(C_a, C_b, eri)
        E_xc = lsda_exc_energy(rho_a, rho_b, weights)

        return E_kin + E_ext + E_H + E_xc + E_nuc
    return total_energy_spin

# @title 9. D4FT Optimisation Loop (Method 2 — Standard D4FT)
# ─────────────────────────────────────────────────────────────
# Direct energy minimisation via gradient descent on W.
# Uses piece-wise constant LR schedule and optional mini-batch SGD.
# ─────────────────────────────────────────────────────────────

def run_d4ft(mol_name: str,
             spin: int = 0,
             max_epoch: int = D4FT_MAX_EPOCH,
             lr_init: float = D4FT_LR_INIT,
             lr_schedule: list = D4FT_LR_STEPS,
             batch_size: int = D4FT_BATCH,
             conv_tol: float = D4FT_CONV_TOL,
             verbose: bool = True,
             record_history: bool = False) -> dict:
    """
    Run standard D4FT (Method 2) on a molecule.

    Returns dict with keys:
        energy      : final total energy (Ha)
        history     : list of (epoch, time, energy) if record_history
        n_epochs    : number of epochs to convergence
        wall_time   : total wall-clock time (s)
    """
    t0 = time.time()

    mol = build_mol(mol_name, spin=spin)
    coords, weights, phi, phi_grad, S, E_nuc, eri, (na, nb) = get_grid_and_basis(mol)
    B = phi.shape[1]

    # Whitening
    D = compute_whitening(S)

    # Atom info for external potential
    atom_coords  = np.array([mol.atom_coord(i) for i in range(mol.natm)], dtype=np.float64)
    atom_charges = np.array([mol.atom_charge(i) for i in range(mol.natm)], dtype=np.float64)

    # Build total energy function
    energy_fn = make_total_energy_fn(
        phi, phi_grad, coords, weights,
        atom_coords, atom_charges, D, E_nuc, eri,  # <-- ADD 'eri' HERE
        use_neural_xc=False,
        batch_size=batch_size if len(weights) > batch_size else None
    )

    # Initialise W (N_occ, B) - CLOSED SHELL ONLY
    key   = jax.random.PRNGKey(0)
    N_occ = na   # Spatial orbitals = total electrons / 2
    W     = jax.random.normal(key, shape=(N_occ, B)) * 0.1

    # Piecewise-constant LR schedule
    boundaries = [ep for ep, _ in lr_schedule]
    values     = [lr_init] + [lr for _, lr in lr_schedule]
    lr_sched   = optax.piecewise_constant_schedule(lr_init, {
        b: v / values[i] for i, (b, v) in enumerate(zip(boundaries, values[1:]))
    })
    optimizer  = optax.adam(lr_sched)
    opt_state  = optimizer.init(W)

    history = []
    prev_E  = jnp.inf

    @jit
    def step(W, opt_state, key):
        loss_fn = lambda w: energy_fn(w, key=key)
        E, grads = value_and_grad(loss_fn)(W)
        updates, new_state = optimizer.update(grads, opt_state)
        new_W = optax.apply_updates(W, updates)
        return new_W, new_state, E

    for epoch in range(max_epoch):
        key, subkey = jax.random.split(key)
        W, opt_state, E = step(W, opt_state, subkey)

        E_val = float(E)
        if record_history:
            history.append((epoch, time.time() - t0, E_val))

        if verbose and epoch % 20 == 0:
            print(f"  [{mol_name}] Epoch {epoch:4d}  E = {E_val:.6f} Ha")

        if abs(E_val - prev_E) < conv_tol and epoch > 10:
            if verbose:
                print(f"  [{mol_name}] Converged at epoch {epoch}  E = {E_val:.6f} Ha")
            break
        prev_E = E_val

    wall_time = time.time() - t0
    return {
        "energy":    float(E),
        "history":   history,
        "n_epochs":  epoch + 1,
        "wall_time": wall_time,
    }


def run_d4ft_spin(mol_name: str,
                  n_unpaired: int,
                  max_epoch: int = D4FT_MAX_EPOCH,
                  **kwargs) -> dict:
    """
    Run spin-polarised D4FT (LSDA) for magnetism experiments.
    n_unpaired: number of unpaired electrons (0 or 2).
    """
    t0   = time.time()
    spin = n_unpaired
    mol  = build_mol(mol_name, spin=spin)
    coords, weights, phi, phi_grad, S, E_nuc, eri, (na, nb) = get_grid_and_basis(mol)
    B = phi.shape[1]

    D_a = compute_whitening(S)   # same S for both spins (same basis)
    D_b = compute_whitening(S)

    atom_coords  = np.array([mol.atom_coord(i) for i in range(mol.natm)])
    atom_charges = np.array([mol.atom_charge(i) for i in range(mol.natm)])

    energy_fn = make_total_energy_fn_spin(
        phi, phi_grad, phi, phi_grad,
        coords, weights, atom_coords, atom_charges,
        D_a, D_b, E_nuc, eri
    )

    key = jax.random.PRNGKey(1)
    W_a = jax.random.normal(key,             shape=(na, B)) * 0.1
    W_b = jax.random.normal(jax.random.fold_in(key,1), shape=(nb, B)) * 0.1

    optimizer = optax.adam(0.05)
    opt_a     = optimizer.init(W_a)
    opt_b     = optimizer.init(W_b)

    @jit
    def step(W_a, W_b, opt_a, opt_b):
        E, grads = value_and_grad(energy_fn, argnums=(0,1))(W_a, W_b)
        upd_a, new_oa = optimizer.update(grads[0], opt_a)
        upd_b, new_ob = optimizer.update(grads[1], opt_b)
        return (optax.apply_updates(W_a, upd_a),
                optax.apply_updates(W_b, upd_b),
                new_oa, new_ob, E)

    prev_E = jnp.inf
    for epoch in range(max_epoch):
        W_a, W_b, opt_a, opt_b, E = step(W_a, W_b, opt_a, opt_b)
        if abs(float(E) - prev_E) < D4FT_CONV_TOL and epoch > 5:
            break
        prev_E = float(E)

    return {"energy": float(E), "n_epochs": epoch+1,
            "wall_time": time.time()-t0}


