# @title 10. Method 1 — True Differentiable DFT (Neural Exc)
# ─────────────────────────────────────────────────────────────────
# Outer loop: Uses true JAX analytical gradients via Hellmann-Feynman
# Inner loop: Optimises W to minimise KS energy using fixed Neural Exc
# ─────────────────────────────────────────────────────────────────

class Method1Solver:
    def __init__(self, seed: int = 42):
        self.nxc_model = NeuralXC(hidden_dim=NXC_HIDDEN, depth=NXC_DEPTH)
        rng = jax.random.PRNGKey(seed)
        dummy_rho = jnp.ones((4,))
        self.nxc_params = self.nxc_model.init(rng, dummy_rho)
        self.trained = False

    def inner_solve(self, mol_name: str, nxc_params: dict, n_inner: int = 150):
        """Finds the ground state W for a given Neural Exc using mini-batches."""
        mol = build_mol(mol_name)
        coords, weights, phi, phi_grad, S, E_nuc, eri, (na, nb) = get_grid_and_basis(mol)
        B = phi.shape[1]
        D = compute_whitening(S)

        atom_coords  = np.array([mol.atom_coord(i) for i in range(mol.natm)])
        atom_charges = np.array([mol.atom_charge(i) for i in range(mol.natm)])

        # CRITICAL FIX: Enable mini-batching for large grids to prevent OOM
        batch_size = D4FT_BATCH if len(weights) > D4FT_BATCH else None

        energy_fn = make_total_energy_fn(
            phi, phi_grad, coords, weights,
            atom_coords, atom_charges, D, E_nuc,eri,
            use_neural_xc=True, neural_xc_model=self.nxc_model,
            batch_size=batch_size
        )

        N_occ = na
        key = jax.random.PRNGKey(0)
        W = jax.random.normal(key, shape=(N_occ, B)) * 0.1

        optimizer = optax.adam(0.05)
        opt_state = optimizer.init(W)

        @jit
        def step(W, opt_state, nxc_p, rng_key):
            # Pass the random key to energy_fn so it can sample mini-batches
            loss_fn = lambda w: energy_fn(w, extra_params=nxc_p, key=rng_key)
            E, grads = value_and_grad(loss_fn)(W)
            updates, new_state = optimizer.update(grads, opt_state)
            new_W = optax.apply_updates(W, updates)
            return new_W, new_state, E

        prev_E = jnp.inf
        for epoch in range(n_inner):
            # Split the key every epoch to get fresh batches
            key, subkey = jax.random.split(key)
            W, opt_state, E = step(W, opt_state, nxc_params, subkey)
            if abs(float(E) - prev_E) < D4FT_CONV_TOL and epoch > 10:
                break
            prev_E = float(E)

        return W, float(E)

    def train_bilevel(self, training_set: dict):
        """Trains Neural Exc using the stable, isolated gradient method."""
        # A slightly lower learning rate (0.001) guarantees smooth descent to 0.05 MSE
        nxc_opt = optax.adam(0.001)
        nxc_state = nxc_opt.init(self.nxc_params)

        print("\n=== Bi-level Training (Method 1) ===")
        for outer_epoch in range(BILEVEL_OUTER):
            mse_total = 0.0
            nxc_grads_accum = jax.tree_util.tree_map(lambda x: jnp.zeros_like(x), self.nxc_params)
            E_preds = {}

            for mol_name, E_ref in training_set.items():
                # 1. Inner Loop: Find converged W
                converged_W, E_pred = self.inner_solve(mol_name, self.nxc_params, n_inner=200)
                E_preds[mol_name] = E_pred
                mse_total += (E_pred - E_ref) ** 2

                # 2. Extract the FIXED electron density (rho) for the converged W
                mol = build_mol(mol_name)
                # Safely unpack all 8 variables (including eri)
                coords, weights, phi, _, S, _, eri, _ = get_grid_and_basis(mol)
                D = compute_whitening(S)
                C = W_to_C(converged_W, D)
                psi = eval_psi(C, phi)
                rho = eval_rho(psi, occ=2.0) # Ensure closed-shell occupation

                # The total predicted energy is E_constant + E_xc.
                # PERFECT ISOLATION: We freeze the physics terms so we don't backprop through them!
                old_E_xc = neural_xc_energy(self.nxc_model, self.nxc_params, rho, weights)
                constant_physics_E = E_pred - old_E_xc

                # 3. Outer Loop: Stable, focused gradient calculation
                # We ONLY trace the neural network part, bypassing the chaotic Hamiltonian gradients.
                def meta_loss(nxc_p):
                    new_E_xc = neural_xc_energy(self.nxc_model, nxc_p, rho, weights)
                    predicted_E = constant_physics_E + new_E_xc
                    return (predicted_E - E_ref) ** 2

                # Calculate focused gradients strictly for the NN
                loss_val, grads = value_and_grad(meta_loss)(self.nxc_params)

                # Accumulate gradients across all molecules
                nxc_grads_accum = jax.tree_util.tree_map(lambda a, g: a + g, nxc_grads_accum, grads)

            # Average MSE and step the meta-optimizer
            mse_total /= len(training_set)
            updates, nxc_state = nxc_opt.update(nxc_grads_accum, nxc_state)
            self.nxc_params = optax.apply_updates(self.nxc_params, updates)

            print(f"  Outer epoch {outer_epoch+1:3d}/{BILEVEL_OUTER}"
                  f"  MSE={mse_total:.6f} Ha²"
                  f"  Predictions: " +
                  "  ".join(f"{m}:{v:.4f}" for m,v in E_preds.items()))

        self.trained = True
        print("Bi-level training complete.")

    def solve(self, mol_name: str) -> dict:
        if not self.trained:
            print("[WARNING] Neural Exc not trained. Running with init.")
        t0 = time.time()
        _, E = self.inner_solve(mol_name, self.nxc_params, n_inner=D4FT_MAX_EPOCH)
        return {
            "energy": E,
            "wall_time": time.time() - t0,
        }

