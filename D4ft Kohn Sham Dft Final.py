    res2 = run_d4ft(tag, verbose=False, record_history=True,
                    batch_size=D4FT_BATCH)
    results_exp3[tag]["M2_energy"]  = res2["energy"]
    results_exp3[tag]["M2_time"]    = res2["wall_time"]
    results_exp3[tag]["M2_history"] = res2["history"]
    print(f"E = {res2['energy']:.4f} Ha  ({res2['wall_time']:.1f}s)  epochs={res2['n_epochs']}")

    # Method 1: Neural Hybrid
    print(f"  Method 1 (Hybrid)...", end=" ", flush=True)
    res1 = method1_solver.solve(tag)
    results_exp3[tag]["M1_energy"]  = res1["energy"]
    results_exp3[tag]["M1_time"]    = res1["wall_time"]
    print(f"E = {res1['energy']:.4f} Ha  ({res1['wall_time']:.1f}s)")

