def build_mol(name: str, spin: int = 0, charge: int = 0,
              basis: str = BASIS) -> gto.Mole:
    """Build and return a PySCF Mole object."""
    mol = gto.Mole()
    mol.atom  = MOLECULES[name]
    mol.basis = basis
    mol.spin  = spin      # 2S  (number of unpaired electrons)
    mol.charge = charge
    mol.unit  = "Angstrom"
    mol.verbose = 0
    mol.build()
    return mol


def get_grid_and_basis(mol: gto.Mole):
    grids = dft.gen_grid.Grids(mol)
    grids.level = 3
    grids.build()

    coords, weights = grids.coords, grids.weights
    ao_vals  = numint.eval_ao(mol, coords, deriv=1)
    phi, phi_grad = ao_vals[0], ao_vals[1:].transpose(1, 2, 0)

    S     = mol.intor("int1e_ovlp")
    E_nuc = mol.energy_nuc()

    # CRITICAL FIX: Extract analytical ERIs for small molecules
    if mol.nao < 200:
        eri = mol.intor("int2e")
    else:
        eri = np.zeros((1,1,1,1)) # Dummy for massive Fullerenes to prevent RAM crash

    n_alpha = (mol.nelectron + mol.spin) // 2
    n_beta  = (mol.nelectron - mol.spin) // 2

    return (coords, weights, phi, phi_grad, S, E_nuc, eri, (n_alpha, n_beta))


def pyscf_lda_energy(name: str, spin: int = 0) -> float:
    """Run PySCF LDA/KS-DFT and return total energy (Ha)."""
    mol = build_mol(name, spin=spin)
    if spin == 0:
        mf = dft.RKS(mol)
    else:
        mf = dft.UKS(mol)
    mf.xc     = XC_LDA
    mf.basis  = BASIS
    mf.verbose = 0
    energy = mf.kernel()
    return energy


def pyscf_ccsd_t_energy(name: str) -> float:
    """Run PySCF RHF → CCSD(T) and return total energy (Ha). Slow — for small mols only."""
    mol = build_mol(name)
    mf  = scf.RHF(mol)
    mf.verbose = 0
    mf.kernel()
    mycc = cc.CCSD(mf)
    mycc.verbose = 0
    mycc.kernel()
    et = mycc.ccsd_t()
    return mf.e_tot + mycc.e_corr + et    # total CCSD(T) energy

